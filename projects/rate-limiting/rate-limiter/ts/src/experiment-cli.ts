import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { renderChart } from "./chart";
import { runExperiment } from "./experiment";
import { renderTable } from "./report";

// EN: `bun run experiment`: runs the burst experiment and writes the results, the table and
//     the chart to `results/`. The chart is drawn from the same object that is saved as JSON,
//     so the picture can never disagree with the numbers.
// PT: `bun run experiment`: roda o experimento de rajada e grava os resultados, a tabela e o
//     gráfico em `results/`. O gráfico é desenhado a partir do mesmo objeto salvo como JSON,
//     então a imagem nunca diverge dos números.

const projectDir = resolve(process.env.PROJECT_DIR ?? join(import.meta.dir, "..", ".."));
const resultsDir = join(projectDir, "results");
mkdirSync(resultsDir, { recursive: true });

const result = runExperiment();
const { limit, windowMs } = result.config;

const markdown = [
	"# Burst experiment",
	"",
	"Generated by `docker compose run --rm experiment`. Do not edit by hand.",
	"",
	`Every algorithm is configured as ${limit} requests per ${windowMs} ms and receives the same ${result.offered.total} requests. The experiment is a simulation with an injected clock, so the numbers do not depend on the machine: the test suite fails when this folder is out of date.`,
	"",
	"## Requests admitted (English)",
	"",
	renderTable(result, "en"),
	"",
	"![Chart](burst.svg)",
	"",
	"## Requisições admitidas (Português)",
	"",
	renderTable(result, "pt"),
	"",
	"![Gráfico](burst.pt-BR.svg)",
	"",
].join("\n");

writeFileSync(join(resultsDir, "burst.json"), `${JSON.stringify(result, null, "\t")}\n`);
writeFileSync(join(resultsDir, "burst.md"), markdown);
writeFileSync(join(resultsDir, "burst.svg"), renderChart(result, "en"));
writeFileSync(join(resultsDir, "burst.pt-BR.svg"), renderChart(result, "pt"));

console.log(renderTable(result, "en"));
console.log(`\nwritten to ${resultsDir}: burst.json, burst.md, burst.svg, burst.pt-BR.svg`);
