function render(language: Language): string {
	const text = TEXT[language];
	const areas = loadAreas(contentDir);
	const miniProjects = loadMiniProjects(contentDir);
	const counts = new Map(checkContent({ contentDir, repoRoot }).areas.map((area) => [area.area, area.actual]));

	const rows = areas.map((area) => {
		const count = counts.get(area.slug) ?? 0;
		const reviewed = existsSync(join(contentDir, area.slug, "review.md"));
		const projects = miniProjects
			.filter((item) => item.area === area.slug)
			.map((item) => {
				const name = basename(item.path);
				// EN: A finished mini-project links to its documentation page, when there is one.
				// PT: Um mini-projeto pronto aponta para sua página de documentação, quando existe.
				// ES: Un mini-proyecto listo apunta a su página de documentación, cuando existe.
				const page = join(repoRoot, "docs", language, area.slug, `${name}.md`);
				if (item.status !== "done") {
					return `${name} (${text.planned})`;
				}
				return existsSync(page) ? `[${name}](${area.slug}/${name}.md)` : `[${name}](../../${item.path})`;
			});
		const review = count === 0 ? "" : reviewed ? text.reviewed : text.pending;
		return `| ${area.name[language]} | ${text.kind[area.kind]} | ${count}/${area.target} | ${review} | ${projects.join(", ") || text.none} |`;
	});

	const questions = [...counts.values()].reduce((sum, value) => sum + value, 0);
	const target = areas.reduce((sum, area) => sum + area.target, 0);
	const done = miniProjects.filter((item) => item.status === "done").length;
	return [
		text.title,
		"",
		text.other,
		"",
		text.intro,
		"",
		text.guides,
		"",
		...text.guideList.map(([file, label]) => `- [${label}](${file})`),
		"",
		text.status,
		"",
		text.totals(questions, target, done, miniProjects.length),
		"",
		text.head,
		"| --- | --- | ---: | --- | --- |",
		...rows,
		"",
	].join("\n");
}

const check = process.argv.includes("--check");
let stale = false;
for (const language of LANGUAGES) {
	const file = join(repoRoot, "docs", language, "README.md");
	const content = render(language);
	if (check) {
		if (readFileSync(file, "utf8") !== content) {
			console.error(`${file} is out of date: run "bun run docs:index"`);
			stale = true;
		}
	} else {
		writeFileSync(file, content);
		console.log(`wrote ${file}`);
	}
}
process.exit(stale ? 1 : 0);
