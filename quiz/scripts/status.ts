// EN: `bun run docs:index [--check]` writes `docs/<language>/README.md` (en, pt, es) from
//     the repository itself: areas, question counts, blind reviews and mini-projects. A status
//     page written by hand goes stale on the next merge, so this one is generated, and
//     `--check` fails in CI when the committed pages no longer match.
// PT: `bun run docs:index [--check]` escreve `docs/<idioma>/README.md` (en, pt, es) a partir
//     do próprio repositório: áreas, contagem de questões, revisões cegas e mini-projetos. Uma
//     página de status escrita à mão fica velha no próximo merge, então esta é gerada, e
//     `--check` falha no CI quando as páginas versionadas já não batem.
// ES: `bun run docs:index [--check]` escribe `docs/<idioma>/README.md` (en, pt, es) a partir
//     del propio repositorio: áreas, número de preguntas, revisiones ciegas y mini-proyectos.
//     Una página de estado escrita a mano queda vieja en el siguiente merge, así que esta se
//     genera, y `--check` falla en CI cuando las páginas versionadas ya no coinciden.

